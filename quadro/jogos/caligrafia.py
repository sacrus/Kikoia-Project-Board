def _catmull_rom(p0: Ponto, p1: Ponto, p2: Ponto, p3: Ponto, t: float) -> Ponto:
    t2 = t * t
    t3 = t2 * t
    x = 0.5 * (
        (2.0 * p1[0])
        + (-p0[0] + p2[0]) * t
        + (2.0 * p0[0] - 5.0 * p1[0] + 4.0 * p2[0] - p3[0]) * t2
        + (-p0[0] + 3.0 * p1[0] - 3.0 * p2[0] + p3[0]) * t3
    )
    y = 0.5 * (
        (2.0 * p1[1])
        + (-p0[1] + p2[1]) * t
        + (2.0 * p0[1] - 5.0 * p1[1] + 4.0 * p2[1] - p3[1]) * t2
        + (-p0[1] + 3.0 * p1[1] - 3.0 * p2[1] + p3[1]) * t3
    )
    return (x, y)


def amostrar_traco(pontos: Traco, passo: float = 0.014) -> Traco:
    """Interpola um traço com curvas Catmull-Rom e reamostra a distância uniforme."""
    if len(pontos) <= 1:
        return list(pontos)
    if len(pontos) == 2:
        p1, p2 = pontos
        dist = math.hypot(p2[0] - p1[0], p2[1] - p1[1])
        n = max(2, int(dist / passo))
        return [(p1[0] + (p2[0] - p1[0]) * i / n, p1[1] + (p2[1] - p1[1]) * i / n) for i in range(n + 1)]

    # Gera curva densa Catmull-Rom
    denso: Traco = []
    m = len(pontos)
    for i in range(m - 1):
        p0 = pontos[max(0, i - 1)]
        p1 = pontos[i]
        p2 = pontos[i + 1]
        p3 = pontos[min(m - 1, i + 2)]
        sub = 20
        for s in range(sub):
            denso.append(_catmull_rom(p0, p1, p2, p3, s / sub))
    denso.append(pontos[-1])

    # Reamostra a passo aproximadamente uniforme
    saida: Traco = [denso[0]]
    acum = 0.0
    for i in range(1, len(denso)):
        ax, ay = denso[i - 1]
        bx, by = denso[i]
        seg = math.hypot(bx - ax, by - ay)
        if seg < 1e-6:
            continue
        acum += seg
        if acum >= passo:
            saida.append((bx, by))
            acum = 0.0
    if saida[-1] != denso[-1]:
        saida.append(denso[-1])
    return saida


def tracos_do_caractere(caractere: str) -> list[Traco]:
    """Devolve os traços suavizados de uma letra cursiva ou número."""
    brutos = TODOS_CARACTERES.get(caractere.lower())
    if not brutos:
        return []
    return [amostrar_traco(t) for t in brutos]
